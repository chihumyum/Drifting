import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { buildDriftingAgentCapabilityManifest } from '../src/renderer/lib/agent/runtime/drifting-agent-capability-manifest';

const coreDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(
  coreDirectory,
  'docs/agent-runtime/acceptance/agent-capabilities.json',
);
const markdownPath = path.join(
  coreDirectory,
  'docs/agent-runtime/acceptance/agent-capabilities.md',
);
const repositoryDirectory = path.resolve(coreDirectory, '..');

const documentationRequirements = [
  {
    path: path.join(repositoryDirectory, 'AGENTS.md'),
    required: ['Every completed feature milestone must update', 'agent-capabilities.md'],
  },
  {
    path: path.join(coreDirectory, 'README.md'),
    required: ['agent-capabilities.md', 'CURRENT_STATUS.md', 'ROADMAP.md'],
  },
  {
    path: path.join(coreDirectory, 'docs/agent-runtime/ROADMAP.md'),
    required: [
      'A milestone is complete only when',
      'acceptance/agent-capabilities.json',
      'acceptance/agent-capabilities.md',
      'acceptance/CURRENT_STATUS.md',
    ],
  },
  {
    path: path.join(coreDirectory, 'docs/agent-runtime/acceptance/CURRENT_STATUS.md'),
    required: [
      'agent-capabilities.json',
      'agent-capabilities.md',
      '../ROADMAP.md',
      'agent:capabilities:check',
    ],
  },
] as const;

async function checkDocumentationContract(): Promise<string[]> {
  const failures: string[] = [];
  for (const requirement of documentationRequirements) {
    let contents = '';
    try {
      contents = await readFile(requirement.path, 'utf8');
    } catch {
      failures.push(`${path.relative(repositoryDirectory, requirement.path)} is missing`);
      continue;
    }
    for (const marker of requirement.required) {
      if (!contents.includes(marker)) {
        failures.push(
          `${path.relative(repositoryDirectory, requirement.path)} is missing "${marker}"`,
        );
      }
    }
    if (/\b\d+\s+of\s+\d+\s+write tools\b/i.test(contents)) {
      failures.push(
        `${path.relative(repositoryDirectory, requirement.path)} contains a hand-maintained write count`,
      );
    }
  }
  return failures;
}

function codeList(values: readonly string[]): string {
  return values.map((value) => `\`${value}\``).join(', ');
}

