async function main(): Promise<void> {
  const manifest = buildDriftingAgentCapabilityManifest();
  const expected = `${JSON.stringify(manifest, null, 2)}\n`;
  const expectedMarkdown = renderMarkdown(manifest);
  const check = process.argv.slice(2).includes('--check');

  if (check) {
    let actual = '';
    let actualMarkdown = '';
    try {
      actual = await readFile(outputPath, 'utf8');
    } catch {
      // The mismatch below gives one stable remediation command.
    }
    try {
      actualMarkdown = await readFile(markdownPath, 'utf8');
    } catch {
      // The mismatch below gives one stable remediation command.
    }
    const documentationFailures = await checkDocumentationContract();
    if (
      actual !== expected ||
      actualMarkdown !== expectedMarkdown ||
      documentationFailures.length > 0
    ) {
      process.stderr.write(
        'Agent capability evidence is stale. Run `pnpm agent:capabilities:generate`.\n',
      );
      if (documentationFailures.length > 0) {
        process.stderr.write(`${documentationFailures.join('\n')}\n`);
      }
      process.exitCode = 1;
    } else {
      process.stdout.write('Agent capability evidence is current.\n');
    }
  } else {
    await Promise.all([
      writeFile(outputPath, expected, 'utf8'),
      writeFile(markdownPath, expectedMarkdown, 'utf8'),
    ]);
    process.stdout.write(
      `${path.relative(coreDirectory, outputPath)} and ${path.relative(
        coreDirectory,
        markdownPath,
      )} updated.\n`,
    );
  }
}

void main().catch((error: unknown) => {
  process.stderr.write(
    `${error instanceof Error ? (error.stack ?? error.message) : String(error)}\n`,
  );
  process.exitCode = 1;
});
