import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';
const result = await build({ entryPoints: ['src/shared/startup-preferences.ts'], bundle: true, write: false,
  format: 'iife', target: 'es2021', legalComments: 'none', banner: { js: '// Generated by pnpm locales:bootstrap. Edit src/shared/startup-preferences.ts.' } });
const output = result.outputFiles[0].text;
if (process.argv.includes('--check')) assert.equal(readFileSync('public/startup.js', 'utf8'), output, 'Run pnpm locales:bootstrap');
else writeFileSync('public/startup.js', output);
